#!/usr/bin/env bun
/**
 * Writes `src/config/bundled-prompts.generated.ts`: every Markdown prompt under
 * `src/prompts/`, keyed by its path relative to that directory. Prompt overrides
 * (`src/config/prompt-overrides.ts`) use it to find the bundled text an override
 * file replaces. Run `bun run gen:prompts` after adding, moving, or removing a
 * prompt file.
 */
import * as path from "node:path";
import { Glob } from "bun";

const SRC_DIR = path.join(import.meta.dir, "../src");
const PROMPTS_DIR = path.join(SRC_DIR, "prompts");
const OUTPUT = path.join(SRC_DIR, "config/bundled-prompts.generated.ts");

const files = Array.from(new Glob("**/*.md").scanSync(PROMPTS_DIR))
	.map(file => file.split(path.sep).join("/"))
	.sort();

const lines = [
	"// Generated by scripts/gen-bundled-prompts.ts (`bun run gen:prompts`). Do not edit.",
	...files.map((file, index) => `import p${index} from "../prompts/${file}" with { type: "text" };`),
	"",
	"/** Every bundled Markdown prompt, keyed by its path under `src/prompts/`. */",
	"export const BUNDLED_PROMPTS: ReadonlyMap<string, string> = new Map([",
	...files.map((file, index) => `\t["${file}", p${index}],`),
	"]);",
	"",
];

await Bun.write(OUTPUT, lines.join("\n"));
console.log(`Wrote ${files.length} prompts to ${path.relative(process.cwd(), OUTPUT)}`);
